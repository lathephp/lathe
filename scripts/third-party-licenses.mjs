// Writes THIRD-PARTY-LICENSES.md from `pnpm licenses list --prod --json` and fails when a
// production dependency's licence is not on the allowed list.
// Usage: node scripts/third-party-licenses.mjs [--input licenses.json] [--output THIRD-PARTY-LICENSES.md]
// Without --input it runs pnpm itself. It exits 1 and names each package whose licence is not allowed.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';

const allowed = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD', 'BlueOak-1.0.0', 'CC0-1.0']);

const args = process.argv.slice(2);
const option = (name) => {
  const index = args.indexOf(name);
  return index === -1 ? undefined : args[index + 1];
};

const json = option('--input')
  ? readFileSync(option('--input'), 'utf8')
  : execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const output = option('--output') ?? 'THIRD-PARTY-LICENSES.md';

// An SPDX expression passes when every part joined by AND is allowed, or any part joined by OR is.
const permits = (expression) => {
  const text = expression.replace(/[()]/g, '').trim();
  if (/\sOR\s/.test(text)) return text.split(/\s+OR\s+/).some(permits);
  return text.split(/\s+AND\s+/).every((part) => allowed.has(part.trim()));
};

const packages = Object.entries(JSON.parse(json))
  .flatMap(([license, list]) => list.map((entry) => ({ ...entry, license })))
  .sort((a, b) => a.name.localeCompare(b.name));

const refused = packages.filter((entry) => !permits(entry.license));
if (refused.length > 0) {
  for (const entry of refused) process.stderr.write(`not allowed: ${entry.name}@${entry.versions.join(', ')} (${entry.license})\n`);
  process.exit(1);
}

const rows = packages.map((entry) => `| ${entry.name} | ${entry.versions.join(', ')} | ${entry.license} |`);
writeFileSync(
  output,
  [
    '# Third-party licenses',
    '',
    'The JavaScript packages bundled into Lathe\'s built assets, with their licenses. Generated by `node scripts/third-party-licenses.mjs` from `pnpm licenses list --prod --json`.',
    '',
    '| Package | Version | License |',
    '|---|---|---|',
    ...rows,
    '',
  ].join('\n'),
);
process.stdout.write(`${packages.length} packages written to ${output}\n`);
